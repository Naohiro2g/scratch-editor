export type MessageKey = keyof (typeof messages)['en']
export const messageKeys = Object.keys(messages.en) as MessageKey[]

export const resolveLocale = (languages: readonly string[]): Locale => {
  for (const language of languages) {
    const normalized = language.toLowerCase()
    if (normalized === 'ja-hira') return 'ja-Hira'
    const base = normalized.split('-')[0]
    if (base === 'ja') return 'ja'
    if (base === 'en') return 'en'
  }
  return 'en'
}

export const translate = (
  locale: Locale,
  key: MessageKey,
  values: Readonly<Record<string, string | number>> = {},
): string =>
  messages[locale][key].replace(/\{([^}]+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder,
  )
